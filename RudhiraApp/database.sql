-- Table 1: volunteers = people who can log in -------------------------
USE if0_43275261_rudhira;
CREATE TABLE IF NOT EXISTS volunteers (
    id            INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    username      VARCHAR(50)  NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,            -- created by PHP password_hash(), never plain text
    name          VARCHAR(100) NOT NULL,
    created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

-- Table 2: students = the blood donors --------------------------------
CREATE TABLE IF NOT EXISTS students (
    id             INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    name           VARCHAR(100) NOT NULL,
    roll_no        VARCHAR(30)  NOT NULL UNIQUE,    -- the PDF "Student Code", e.g. 2YB+001
    blood_group    ENUM('A+','A-','B+','B-','AB+','AB-','O+','O-') NOT NULL,
    contact_number VARCHAR(15)  NULL,               -- NULL when the PDF has no valid number
    place          VARCHAR(50)  NULL,               -- district / place
    year           VARCHAR(10)  NULL,               -- not in the PDF
    department     VARCHAR(20)  NULL,
    last_donation  DATE NULL,                       -- not in the PDF
    donor_status   ENUM('Available','Not Available') NOT NULL DEFAULT 'Available',
    registered_at  DATETIME NULL,                   -- the PDF "Timestamp"
    created_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_students_blood_group (blood_group),
    INDEX idx_students_place (place)
) ENGINE=InnoDB;

